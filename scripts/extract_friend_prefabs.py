PREFABS = [
    ("PerfectMaze21_1", PERFECT_MAZE_21_1),
    ("PerfectMaze21_2", PERFECT_MAZE_21_2),
    ("PerfectMaze21_3", PERFECT_MAZE_21_3),
    ("PerfectMaze21_4", PERFECT_MAZE_21_4),
    ("Rooms21_1", ROOMS_21_1),
    ("Rooms21_2", ROOMS_21_2),
    ("Labyrinth21_1", LABYRINTH_21_1),
    ("Labyrinth21_2", LABYRINTH_21_2),
]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=str,
        default="eval_levels/friend/prefabs_21x21.npz",
    )
    args = parser.parse_args()

    os.makedirs(os.path.dirname(args.output), exist_ok=True)

    levels = []
    names = []
    for name, s in PREFABS:
        lvl = Level.from_str(s.strip())
        levels.append(lvl)
        names.append(name)
        print(
            f"  {name}: {int(lvl.width)}x{int(lvl.height)}, "
            f"agent={tuple(int(x) for x in lvl.agent_pos)}, "
            f"goal={tuple(int(x) for x in lvl.goal_pos)}"
        )

    stacked = Level.stack(levels)
    data = {
        "wall_map": np.asarray(stacked.wall_map),
        "goal_pos": np.asarray(stacked.goal_pos),
        "agent_pos": np.asarray(stacked.agent_pos),
        "agent_dir": np.asarray(stacked.agent_dir),
        "width": np.asarray(stacked.width),
        "height": np.asarray(stacked.height),
        "names": np.asarray(names),
    }
    np.savez(args.output, **data)
    print(f"\nSaved {len(names)} larger prefab mazes to {args.output}")
    print(f"  wall_map shape: {data['wall_map'].shape}")
    print(f"  first sample:\n{levels[0].to_str()}")


if __name__ == "__main__":
    main()
